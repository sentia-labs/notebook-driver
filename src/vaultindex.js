import fs from 'node:fs';
import path from 'node:path';
import { writeFileAtomic } from './util.js';

// vault/index.md is the catalog an agent reads first (Karpathy's LLM-wiki "index"). It is built
// by code from each note's frontmatter, so it can't drift from the files; the agent keeps
// `title` and `description` accurate instead of editing the index.

const JOURNAL = ['daily', 'weekly', 'monthly', 'quarterly', 'yearly'];

const SECTIONS = [
  ['Projects', (n) => n.type === 'project'],
  ['Areas', (n) => n.type === 'area'],
  ['People', (n) => n.type === 'person'],
  ['Collections', (n) => n.type === 'collection'],
  ['Topics', (n) => n.type === 'topic'],
  ['Concepts and ideas', (n) => n.type === 'concept' || n.type === 'idea'],
  ['Decisions', (n) => n.type === 'decision'],
  ['References', (n) => ['reference', 'resource', 'book', 'article', 'place', 'organization'].includes(n.type)],
  ['Syntheses', (n) => n.type === 'synthesis'],
];

function archived(n) {
  return n.rel.startsWith('vault/archive/') || String(n.frontmatter.status ?? '') === 'archived';
}

function line(n) {
  const fm = n.frontmatter;
  const bits = [];
  if (fm.status && !['active', 'stable'].includes(String(fm.status))) bits.push(String(fm.status));
  const updated = fm.updated ? String(fm.updated).slice(0, 10) : null;
  if (updated) bits.push(`updated ${updated}`);
  if (n.sources.length) bits.push(`${n.sources.length} page${n.sources.length > 1 ? 's' : ''}`);
  const desc = n.description ? ` — ${n.description.replace(/\s+/g, ' ').slice(0, 200)}` : '';
  return `- [[${n.name}|${n.title}]]${desc}${bits.length ? ` · ${bits.join(' · ')}` : ''}`;
}

export function buildIndex(library) {
  const notes = library.notes().filter((n) => !['index', 'log'].includes(n.name) || n.rel.split('/').length > 2);
  const used = new Set();
  const out = [
    '# Index',
    '',
    '> Every note in this vault, generated by `nbd` from frontmatter. Agents: read this first, and',
    '> keep each note\'s `title` and `description` accurate instead of editing this file.',
    '',
  ];
  const overview = notes.find((n) => n.rel === 'vault/overview.md');
  if (overview) {
    const what = (overview.description || 'who the human is and what they are working on').replace(/[.\s]+$/, '');
    out.push(`Start with [[overview]] — ${what}.`, '');
    used.add(overview.rel);
  }
  for (const [title, pred] of SECTIONS) {
    const list = notes.filter((n) => !used.has(n.rel) && !archived(n) && pred(n)).sort((a, b) => a.title.localeCompare(b.title));
    if (!list.length) continue;
    list.forEach((n) => used.add(n.rel));
    out.push(`## ${title} (${list.length})`, ...list.map(line), '');
  }

  const journal = notes.filter((n) => !used.has(n.rel) && (n.rel.startsWith('vault/journal/') || JOURNAL.includes(n.type)));
  if (journal.length) {
    out.push(`## Journal (${journal.length})`);
    const future = journal.find((n) => n.name === 'future-log');
    if (future) out.push(`- [[future-log|Future log]] — ${future.description || 'what is scheduled for coming months'}`);
    for (const kind of JOURNAL) {
      const list = journal.filter((n) => n.rel.startsWith(`vault/journal/${kind}/`)).sort((a, b) => b.name.localeCompare(a.name));
      if (!list.length) continue;
      if (kind === 'daily') {
        const byMonth = new Map();
        for (const n of list) byMonth.set(n.name.slice(0, 7), [...(byMonth.get(n.name.slice(0, 7)) ?? []), n]);
        for (const [month, days] of byMonth) out.push(`- Daily ${month}: ${days.map((d) => `[[${d.name}]]`).join(' · ')}`);
      } else {
        out.push(`- ${kind[0].toUpperCase()}${kind.slice(1)}: ${list.map((n) => `[[${n.name}]]${n.frontmatter.review === 'done' ? ' ✓' : ''}`).join(' · ')}`);
      }
    }
    journal.forEach((n) => used.add(n.rel));
    const loose = journal.filter((n) => n.name !== 'future-log' && !JOURNAL.some((k) => n.rel.startsWith(`vault/journal/${k}/`)));
    out.push(...loose.map(line));
    out.push('');
  }

  const questions = notes.filter((n) => !used.has(n.rel) && n.rel.startsWith('vault/inbox/'));
  questions.forEach((n) => used.add(n.rel));
  const openQ = questions.filter((n) => String(n.frontmatter.status ?? 'open') === 'open');
  if (questions.length) {
    out.push(`## Questions for the human (${openQ.length} open of ${questions.length})`);
    out.push(...openQ.map((n) => `- [[${n.name}|${n.title}]]`));
    out.push('');
  }

  const arch = notes.filter((n) => !used.has(n.rel) && archived(n)).sort((a, b) => a.title.localeCompare(b.title));
  arch.forEach((n) => used.add(n.rel));
  if (arch.length) out.push(`## Archive (${arch.length})`, ...arch.map(line), '');

  const rest = notes.filter((n) => !used.has(n.rel) && n.rel !== 'vault/log.md').sort((a, b) => a.title.localeCompare(b.title));
  if (rest.length) out.push(`## Other (${rest.length})`, ...rest.map(line), '');

  if (notes.length === 0) out.push('_The vault is empty. It fills in as you write notebook pages._', '');
  return out.join('\n');
}

/** Rewrite vault/index.md if it changed. Returns true when the file was written. */
export function writeIndex(library) {
  const file = path.join(library.paths.vault, 'index.md');
  const text = buildIndex(library);
  let current = null;
  try {
    current = fs.readFileSync(file, 'utf8');
  } catch {}
  if (current === text) return false;
  writeFileAtomic(file, text);
  return true;
}
